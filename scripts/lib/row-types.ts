// src/lib/rows.ts, written from the tables the migrations leave (./schema-doc.ts): each table's row as D1 hands it
// back, column for column, so a query's row type is taken from the schema rather than typed again by hand.

import type { Column, Table } from "./schema-doc.ts";

/** The TypeScript a declared SQLite type reads as. */
function valueOf(declared: string): string {
  if (declared === "") return "string | number";
  if (declared.includes("BLOB")) return "ArrayBuffer";
  return declared.includes("INT") || /REAL|FLOA|DOUB|NUMERIC/.test(declared) ? "number" : "string";
}

/**
 * Columns declared nullable that a guard trigger holds whole (migration 0169): a visit's client, kind, start and end,
 * which D1 cannot make NOT NULL in place, since its client's column points at people.
 */
const HELD_WHOLE: Readonly<Record<string, readonly string[]>> = {
  appointments: ["person_id", "type", "window_start", "window_end"],
};

/** The TypeScript a column reads as: its value, or null as well where the column may be empty. */
function typeOf(table: string, column: Column): string {
  const value = valueOf(column.type.toUpperCase());
  const whole = column.notNull || column.primaryKey || (HELD_WHOLE[table] ?? []).includes(column.name);
  return whole ? value : `${value} | null`;
}

/** A column's name as a property: quoted where it is not a plain identifier. */
const keyOf = (name: string): string => (/^[a-z_][a-z0-9_]*$/i.test(name) ? name : JSON.stringify(name));

export function rowTypes(tables: readonly Table[]): string {
  const rows = tables.map((table) => {
    const columns = table.columns.map((column) => `    readonly ${keyOf(column.name)}: ${typeOf(table.name, column)};`);
    return `  readonly ${keyOf(table.name)}: {\n${columns.join("\n")}\n  };`;
  });
  return `// Generated by \`npm run schema\` from the migrations (scripts/lib/row-types.ts). Do not edit.
//
// Each table's row as D1 hands it back, column for column: a NOT NULL column is its type, any other may be null. A
// query takes its row type from here, whole or in part: \`.all<Pick<Rows["people"], "id" | "name">>()\`.

export interface Rows {
${rows.join("\n")}
}

/** A table in D1, by name. */
export type TableName = keyof Rows;
`;
}
