// What a visit's write keeps up beside it (src/domain/visits/visit-upkeep.ts), as SQL text: the domain's own statements,
// each with its values written in. ./every-visit-upkeep.ts holds them for everyone who has a visit, for the seeds that
// write visits by hand, which load where the Worker's types do not; `npm run gen` writes it from here.

import { visitUpkeep, type Whose } from "../../src/domain/visits/visit-upkeep.ts";
import { sqlLiteral } from "./sql-literal.ts";

type Value = string | number | null;

interface Recorded {
  readonly sql: string;
  readonly values: readonly Value[];
  bind: (...values: Value[]) => Recorded;
}

const recorded = (sql: string, values: readonly Value[] = []): Recorded => ({
  sql,
  values,
  bind: (...bound) => recorded(sql, bound),
});

/** Stands in for D1, keeping each statement prepared and what it is bound to rather than running it. */
const RECORDING = { prepare: (sql: string) => recorded(sql) } as unknown as D1Database;

/** A seed's visits are on the books from when it runs, by the database's own clock. */
const SEEDED_AT = "__seeded_at__";
const DATABASE_NOW = "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";

export function visitUpkeepSql(whose: Whose): string[] {
  return visitUpkeep(RECORDING, whose, SEEDED_AT).map((statement) => {
    const { sql, values } = statement as unknown as Recorded;
    const text = sql
      .replace(/\?(\d+)/g, (_, index: string) => sqlLiteral(values[Number(index) - 1] ?? null))
      .replaceAll(sqlLiteral(SEEDED_AT), DATABASE_NOW);
    return `${text.replace(/\s+/g, " ").trim()};`;
  });
}

const EVERYONE = "__everyone__";

/** The same, for everyone who has a visit. */
export const everyVisitUpkeepSql = (): string[] =>
  visitUpkeepSql({ people: [EVERYONE] }).map((sql) =>
    sql.replaceAll(`(SELECT value FROM json_each('["${EVERYONE}"]'))`, "(SELECT person_id FROM appointments)"),
  );

/** ./every-visit-upkeep.ts, as `npm run gen` writes it. */
export function everyVisitUpkeepModule(): string {
  const lines = everyVisitUpkeepSql().map((sql) => `  ${JSON.stringify(sql)},`);
  return `// Generated by \`npm run gen\` from src/domain/visits/visit-upkeep.ts (./visit-upkeep-sql.ts). Do not edit.
//
// What the visits a seed writes by hand keep up beside them, for everyone who has a visit, as the domain's own writes
// keep it: run after the seed's own statements.

export const EVERY_VISIT_UPKEEP: readonly string[] = [
${lines.join("\n")}
];
`;
}
